"""Moves every actor state of c4_act1.c / c4_wiz.c into one bank-0 table.

The game code is spread over switchable banks, so the states (read by all
of it) live in bank 0 as `states[]`; `s_name` becomes a macro for
`states[i]`.  Think routines are referred to by number and called through
think_call() (bank 0), which makes the banked calls.  A saved object keeps
its state as an index into states[].

Usage: gen_states.py SRCDIR OUTDIR   (writes states.c, states.h)
"""
import re, sys, os

STATE_RE = re.compile(r'^\s*const\s+statetype\s+(\w+)\s*=\s*\{([^}]*)\}\s*;', re.M)
ARRAY_RE = re.compile(r'^\s*const\s+statetype\s+(\w+)\s*\[(\d+)\]\s*=\s*\{(.*?)\}\s*;', re.M | re.S)


def parse(files):
    states = []         # (name, shape, tics, think, next)
    arrays = {}         # name -> (first index, count)
    for fn in files:
        src = open(fn).read()
        items = []
        for m in STATE_RE.finditer(src):
            items.append((m.start(), 's', m))
        for m in ARRAY_RE.finditer(src):
            items.append((m.start(), 'a', m))
        items.sort(key=lambda t: t[0])
        for _, kind, m in items:
            if kind == 's':
                f = [x.strip() for x in m.group(2).split(',')]
                assert len(f) == 4, m.group(0)
                states.append((m.group(1), f[0], f[1], f[2].lstrip('&'), f[3].lstrip('&')))
            else:
                name, n, body = m.group(1), int(m.group(2)), m.group(3)
                elems = re.findall(r'\{([^}]*)\}', body)
                assert len(elems) == n
                arrays[name] = (len(states), n)
                for i, e in enumerate(elems):
                    f = [x.strip() for x in e.split(',')]
                    states.append(('%s[%d]' % (name, i), f[0], f[1], f[2].lstrip('&'), f[3].lstrip('&')))
    return states, arrays


def strip_states(src):
    """remove state definitions and extern state declarations from a source"""
    src = ARRAY_RE.sub('', src)
    src = STATE_RE.sub('', src)
    src = re.sub(r'^\s*extern\s+const\s+statetype\s+[^;]*;\s*$', '', src, flags=re.M)
    return src


def main(srcdir, outdir):
    files = [os.path.join(srcdir, f) for f in ('c4_act1.c', 'c4_wiz.c')]
    states, arrays = parse(files)
    index = {}
    for i, s in enumerate(states):
        index[s[0]] = i
    thinks = []
    for s in states:
        t = s[3]
        if t != 'NULL' and t not in thinks:
            thinks.append(t)

    def ref(n):
        if n == 'NULL':
            return 'NULL'
        return '&states[%d]' % index[n]

    h = ['/* generated by tools/gen_states.py */', '#ifndef STATES_H', '#define STATES_H', '']
    h.append('#define NUMSTATES %d' % len(states))
    h.append('extern const statetype states[NUMSTATES];')
    h.append('#define STATE_INDEX(p) ((u16)((p) - states))')
    h.append('')
    h.append('enum {TH_NONE%s};' % ''.join(', TH_%s' % t for t in thinks))
    for t in thinks:
        h.append('void %s(objtype *ob) __banked;' % t)
    h.append('void think_call(u8 think, objtype *ob);')
    h.append('')
    for s in states:
        if '[' in s[0]:
            continue
        h.append('#define %s (states[%d])' % (s[0], index[s[0]]))
    for name, (first, n) in arrays.items():
        h.append('#define %s (&states[%d])' % (name, first))
    h.append('#endif')
    open(os.path.join(outdir, 'states.h'), 'w').write('\n'.join(h) + '\n')

    c = ['/* generated by tools/gen_states.py */', '#include "def.h"', '',
         '#define SH(p) ((p) ? (u8)((p) - FIRSTSCALEPIC) : 0)', '',
         'const statetype states[NUMSTATES] = {']
    for s in states:
        th = 'TH_NONE' if s[3] == 'NULL' else 'TH_' + s[3]
        c.append('    {SH(%s), %s, %s, %s},   /* %d %s */' % (s[1], s[2], th, ref(s[4]), index[s[0]], s[0]))
    c.append('};')
    c.append('')
    c.append('void think_call(u8 think, objtype *ob)')
    c.append('{')
    c.append('    switch (think)')
    c.append('    {')
    for t in thinks:
        c.append('    case TH_%s: %s(ob); break;' % (t, t))
    c.append('    }')
    c.append('}')
    open(os.path.join(outdir, 'states.c'), 'w').write('\n'.join(c) + '\n')
    print('states', len(states), 'thinks', len(thinks))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2])
