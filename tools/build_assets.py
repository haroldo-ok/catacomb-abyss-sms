"""Builds all ROM data: gen/data.bin (banks from DATA_FIRST_BANK) + gen/assets.h + gen/assets_tab.c"""
import os, sys, pickle, hashlib
from packer import Packer
HERE = os.path.dirname(os.path.abspath(__file__))
GEN = os.path.join(HERE, '..', 'gen')
CACHE = os.path.join(HERE, '..', 'gen', 'cache')
DATA_FIRST_BANK = 8
os.makedirs(GEN, exist_ok=True)
os.makedirs(CACHE, exist_ok=True)

def cached(key, fn):
    """cache expensive conversions keyed on tool sources"""
    h = hashlib.md5(key.encode())
    for f in ('fullscreen.py', 'screens_sms.py', 'fonts.py', 'common.py', 'finale.py', 'game_assets.py'):
        h.update(open(os.path.join(HERE, f), 'rb').read())
    path = os.path.join(CACHE, h.hexdigest() + '.bin')
    if os.path.exists(path):
        return open(path, 'rb').read()
    d = fn()
    open(path, 'wb').write(d)
    return d

H = []      # header lines
C = []      # bank-0 table source lines

def main():
    pk = Packer(DATA_FIRST_BANK)
    import screens_sms
    banks = []
    for i, n in enumerate(screens_sms.PIC_SCREENS):
        blob = cached('scr:' + n, lambda: screens_sms.convert(n))
        b, a = pk.add(n, blob, whole_bank=True)
        banks.append(b)
        H.append('#define %s %d' % (n.upper(), i))
    H.append('#define NUM_PIC_SCREENS %d' % len(banks))
    H.append('extern const u8 screen_bank[];')
    C.append('const u8 screen_bank[] = {%s};' % ','.join(map(str, banks)))

    import render_gen
    render_gen.build(pk, H, C)
    render_gen.build_maps(pk, H, C)

    import game_assets
    game_assets.build(pk, H, C, cached)

    nb = pk.write(os.path.join(GEN, 'data.bin'))
    H.append('#define DATA_FIRST_BANK %d' % DATA_FIRST_BANK)
    H.append('#define DATA_NUM_BANKS %d' % nb)
    with open(os.path.join(GEN, 'assets.h'), 'w') as f:
        f.write('/* generated by tools/build_assets.py */\n#ifndef ASSETS_H\n#define ASSETS_H\n#include "hw.h"\n')
        f.write('\n'.join(H) + '\n#endif\n')
    import re as _re
    with open(os.path.join(GEN, 'assets.inc'), 'w') as f:
        f.write(';; generated by tools/build_assets.py\n')
        for l in H:
            m = _re.match(r'#define (\w+) (0x[0-9A-Fa-f]+|\d+)$', l)
            if m:
                f.write('%s = %s\n' % (m.group(1), m.group(2)))
    with open(os.path.join(GEN, 'assets_tab.c'), 'w') as f:
        f.write('/* generated by tools/build_assets.py */\n#include "assets.h"\n')
        f.write('\n'.join(C) + '\n')
    with open(os.path.join(GEN, 'data_banks.txt'), 'w') as f:
        f.write('%d %d\n' % (DATA_FIRST_BANK, nb))
    print('data banks', nb)

if __name__ == '__main__':
    main()
